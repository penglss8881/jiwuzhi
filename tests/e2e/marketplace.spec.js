import { test, expect } from '@playwright/test'
import { mockApp } from './fixtures.js'

test('unified search opens a public profile, goods, moments and chat', async ({ page }) => {
  const { requests } = await mockApp(page)
  await page.goto('/plaza')
  await page.getByRole('textbox', { name: '搜索商品或用户', exact: true }).fill('鹿鸣')
  await page.getByRole('button', { name: '搜索', exact: true }).click()
  await page.getByRole('tab', { name: /用户/ }).click()
  await page.getByRole('link', { name: /鹿鸣.*查看主页/ }).click()
  await expect(page).toHaveURL('/users/2')
  await expect(page.getByRole('heading', { name: '鹿鸣', exact: true })).toBeVisible()
  await expect(page.locator('.item-card')).toHaveCount(12)
  await page.getByRole('tab', { name: 'TA 的动态' }).click()
  await expect(page.locator('.profile-moments .post-card')).toHaveCount(1)
  await expect(page.locator('.profile-moments')).not.toContainText('把闲置书架整理了一遍')
  await page.locator('.profile-moments').getByRole('link', { name: /查看动态/ }).click()
  await expect(page).toHaveURL('/posts/1')
  await page.goBack()
  await page.getByRole('link', { name: '发私信', exact: true }).click()
  await expect(page).toHaveURL('/chat?uid=2')
  await expect(page.getByRole('textbox', { name: '消息内容' })).toBeVisible()
  expect(requests.some(r => r.path === '/items' && r.query.ownerId === '2')).toBe(true)
  expect(requests.some(r => r.path === '/posts' && r.query.authorId === '2')).toBe(true)
  expect(requests.some(r => r.path === '/conversations' && r.body.otherUserId === 2)).toBe(true)
})

test('empty, failed and missing user states; refresh and mobile layout', async ({ page }) => {
  await mockApp(page)
  await page.goto('/plaza?scope=users')
  await expect(page.getByText('想找谁？在上方输入账号或昵称')).toBeVisible()
  await page.getByRole('textbox', { name: '搜索商品或用户', exact: true }).fill('不存在的用户')
  await page.getByRole('button', { name: '搜索', exact: true }).click()
  await expect(page.getByText('没有找到完全匹配的用户')).toBeVisible()
  await page.route('**/api/v1/users/search?**', route => route.fulfill({ status: 503, json: { message: '搜索暂不可用' } }))
  await page.reload()
  await expect(page.getByRole('alert')).toContainText('搜索暂不可用')
  await page.route('**/api/v1/users/999/profile', route => route.fulfill({ status: 404, json: { message: '用户不存在或已停用' } }))
  await page.goto('/users/999')
  await expect(page.getByRole('alert')).toContainText('用户不存在或已停用')
  await page.goto('/users/2')
  await page.reload()
  await expect(page.getByRole('heading', { name: '鹿鸣', exact: true })).toBeVisible()
  await page.screenshot({ path: 'test-results/user-home-desktop.png', fullPage: true, animations: 'disabled' })
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(page.getByRole('link', { name: '发私信', exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: 'test-results/user-home-mobile.png', fullPage: true, animations: 'disabled' })
})

test('new orders use a single purchase price; legacy orders have no action controls', async ({ page }) => {
  const { requests } = await mockApp(page, { orderState: { requestType: 'rent' } })
  await page.goto('/orders/10')
  await expect(page.getByRole('heading', { name: '历史订单（只读）' })).toBeVisible()
  await expect(page.getByRole('button', { name: '模拟支付', exact: true })).toHaveCount(0)
  await page.goto('/items/1')
  await expect(page.getByRole('button', { name: /租借|买断/ })).toHaveCount(0)
  await page.getByRole('button', { name: '立即购买', exact: true }).click()
  await expect(page.getByRole('dialog')).not.toContainText('天数')
  await expect(page.getByRole('dialog')).toContainText('36')
  await page.getByRole('button', { name: '创建订单并继续' }).click()
  await expect(page).toHaveURL('/orders/10')
  const created = requests.find(r => r.path === '/items/1/rent-requests')
  expect(created.body.type).toBe('buyout')
  expect(created.body.expectDays).toBeUndefined()
})

