test('a slow obsolete search response cannot overwrite newer results', async ({ page }) => {
  await mockApp(page)
  await page.route('**/api/v1/items?**', async route => {
    if (new URL(route.request().url()).searchParams.get('keyword') === 'slow') {
      await new Promise(resolve => setTimeout(resolve, 400))
      try { await route.fulfill({ json: [{ itemId: 999, title: '过时结果', category: '图书', ownerId: 2 }] }) } catch { /* Request was canceled. */ }
    } else await route.fallback()
  })
  await page.goto('/plaza')
  await page.getByRole('textbox', { name: '搜索商品或用户', exact: true }).fill('slow')
  await page.getByRole('button', { name: '搜索', exact: true }).click()
  await page.getByRole('textbox', { name: '搜索商品或用户', exact: true }).fill('人间草木')
  await page.getByRole('button', { name: '搜索', exact: true }).click()
  await expect(page.locator('.item-card')).toHaveCount(3)
  await expect(page.locator('.item-card').first()).toContainText('人间草木')
  await page.waitForTimeout(500) // Explicitly wait beyond the obsolete server response.
  await expect(page.getByText('过时结果')).toHaveCount(0)
})
